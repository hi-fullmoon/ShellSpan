import { readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = new URL('../src/lib/petdex/', import.meta.url);
const schema = JSON.parse(await readFile(new URL('diagnostic.schema.json', root), 'utf8'));
const ajv = new Ajv({ code: { source: true, esm: true, lines: true } });
ajv.addSchema(schema);
const source = '// Generated by scripts/generate-petdex-validators.mjs; do not edit.\n'
  + standaloneCode(ajv, {
    isPetdexDiagnostic: 'petdex#/$defs/diagnostic',
    isPetdexCheckResult: 'petdex#/$defs/checkResult',
    isPetdexTestResult: 'petdex#/$defs/testResult',
  });
const output = new URL('diagnostic-validators.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== source) {
    throw new Error('Petdex validators are stale. Run node scripts/generate-petdex-validators.mjs');
  }
} else {
  await writeFile(output, source);
}
