import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {createIndexReader} from './index-reader.mjs';
import {captureValidationSources} from '../native-input-p2/frozen-validation.mjs';
const root=resolve(process.argv[2]);const meta=resolve(root,'.native-input-p3');
const source=JSON.parse(readFileSync(resolve(meta,'import.json'),'utf8'));
const {index,gitDirectory}=createIndexReader(meta,resolve(meta,'imported-index'),source.head);
const indexSha256=createHash('sha256').update(readFileSync(index)).digest('hex');
writeFileSync(resolve(meta,'snapshot-index.json'),JSON.stringify({version:1,root,index,gitDirectory,indexSha256,purpose:'Copied input index, no refs or commit objects; only complete file discovery.'},null,2));
const expected=JSON.parse(readFileSync(resolve(meta,'sources.json'),'utf8'));
const actual=captureValidationSources(root);
writeFileSync(resolve(meta,'source-initialized.json'),JSON.stringify({sourceCount:Object.keys(actual).length,actual},null,2));
const changed=[...new Set([...Object.keys(expected),...Object.keys(actual)])].filter(path=>expected[path]!==actual[path]);
writeFileSync(resolve(meta,'source-difference.json'),JSON.stringify({changed},null,2));
assert.equal(changed.length,0,`Complete imported source set differs: ${changed.slice(0,20).join(', ')}`);
console.log(JSON.stringify({root,sourceCount:Object.keys(actual).length,completeInventory:true,nativeAcceptance:false}));
