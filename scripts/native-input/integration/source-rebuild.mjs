import assert from 'node:assert/strict';
import {cp,mkdir,readdir,readFile,writeFile} from 'node:fs/promises';
import {openSync,closeSync} from 'node:fs';
import {resolve} from 'node:path';
import {randomUUID} from 'node:crypto';
import {spawn} from 'node:child_process';
import {nativeInputBuildDirectory,nativeInputReleaseDirectory} from './resource-paths.mjs';

const root=resolve(import.meta.dirname,'../../..');
const packaged=nativeInputReleaseDirectory(root);
const directory=resolve(root,'artifacts/tests/native-input/integration/source-rebuild',randomUUID());
await mkdir(directory,{recursive:true,mode:0o700});
const clean=resolve(directory,'ShellSpan');await cp(resolve(packaged,'sources/ShellSpan'),clean,{recursive:true});
const x86Linux=process.platform==='linux'&&process.arch==='x64';
const target=process.platform==='darwin'?'macos-arm64':x86Linux?'linux-x86_64-glibc-2.28':'linux-aarch64-glibc-2.36';
const dependencyRoot=x86Linux?resolve(clean,'artifacts/tests/native-input/integration/dependency-cache',target):'artifacts/tests';
const cache=resolve(nativeInputBuildDirectory(clean,dependencyRoot,'prototype'),'upstream');await mkdir(cache,{recursive:true});
for(const name of await readdir(resolve(packaged,'sources')))if(name.endsWith('.tar.gz')||/^(?:bash53|readline83)-\d{3}$/.test(name))await cp(resolve(packaged,'sources',name),resolve(cache,name));
const log=openSync(resolve(directory,'build.log'),'wx',0o600);
const child=spawn('python3',['-B','scripts/native-input/integration/build.py'],{cwd:clean,env:{...process.env,SHELLSPAN_NATIVE_BUILD_ROOT:'artifacts/tests',CARGO_NET_OFFLINE:'true',PYTHONDONTWRITEBYTECODE:'1'},stdio:['ignore',log,log]});
const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',resolve);});closeSync(log);
await writeFile(resolve(directory,'result.json'),JSON.stringify({exitCode:code,sourceRoot:clean,scope:'Fresh packaged source tree, packaged GNU archives and Cargo vendor for the release Bash profile'},null,2));
assert.equal(code,0,`Packaged-source reconstruction failed; ${directory}`);
const name=`catalogue-${target}.json`;
const expected=JSON.parse(await readFile(resolve(packaged,name),'utf8'));
const actual=JSON.parse(await readFile(resolve(clean,'artifacts/tests/native-input/integration/resources/native-input',name),'utf8'));
assert.deepEqual(actual.sources,expected.sources,'Packaged producer sources differ from the signed resource catalogue');
const profileVersion=({id,bashPatchLevel,readlineVersion})=>({id,bashPatchLevel,readlineVersion});
assert.deepEqual(actual.profiles.map(profileVersion),expected.profiles.map(profileVersion));
console.log(JSON.stringify({directory,result:'PASS',profiles:actual.profiles.map(value=>value.id)}));
